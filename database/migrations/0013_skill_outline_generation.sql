CREATE TABLE skill_outline_generation_jobs (
  id CHAR(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  project_id CHAR(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  occupation_id CHAR(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  textbook_source_version_id CHAR(26) CHARACTER SET ascii COLLATE ascii_bin NULL,
  generation_mode ENUM('textbook','model') NOT NULL,
  target_questions INT UNSIGNED NOT NULL,
  status ENUM('queued','running','succeeded','failed') NOT NULL DEFAULT 'queued',
  basis_snapshot_json JSON NOT NULL,
  draft_snapshot_json JSON NULL,
  total_batches INT UNSIGNED NOT NULL DEFAULT 0,
  completed_batches INT UNSIGNED NOT NULL DEFAULT 0,
  generated_point_count INT UNSIGNED NOT NULL DEFAULT 0,
  error_message VARCHAR(2000) NULL,
  result_versions_json JSON NULL,
  created_by CHAR(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  started_at DATETIME(3) NULL,
  finished_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  KEY idx_skill_outline_jobs_scope (occupation_id, created_at),
  KEY idx_skill_outline_jobs_status (status, updated_at),
  CONSTRAINT fk_soj_project FOREIGN KEY (project_id) REFERENCES projects(id),
  CONSTRAINT fk_soj_occupation FOREIGN KEY (occupation_id) REFERENCES project_occupations(id),
  CONSTRAINT fk_soj_textbook FOREIGN KEY (textbook_source_version_id) REFERENCES source_versions(id),
  CONSTRAINT fk_soj_actor FOREIGN KEY (created_by) REFERENCES accounts(id)
) ENGINE=InnoDB;
